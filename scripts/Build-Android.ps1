param(
    [string]$ApiBaseUrl = 'http://192.168.31.245:8000',
    [switch]$Arm64,
    [switch]$PublicServer
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'toolchain-ascii.ps1')
$buildWorkspace = $env:PULS_WORKSPACE_ROOT
$buildMobile = Join-Path $buildWorkspace 'mobile'
$buildArtifacts = Join-Path $buildWorkspace 'artifacts'
if ($PublicServer) {
    $publicBuildState = Get-Content -LiteralPath (Join-Path $buildWorkspace 'runtime/server/status.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    if (-not $publicBuildState.running -or $publicBuildState.url -notmatch '^https://[a-z0-9-]+\.(lhr\.life|trycloudflare\.com|ngrok-free\.app|ngrok-free\.dev|ngrok\.app)$') {
        throw 'A running public server with a verified HTTPS address is required.'
    }
    $ApiBaseUrl = $publicBuildState.url
}
$buildArguments = @('build', 'apk', '--release', '--no-pub', "--dart-define=API_BASE_URL=$ApiBaseUrl")
if ($PublicServer) {
    $publicDiscovery = Get-Content -LiteralPath (Join-Path $buildWorkspace 'runtime/server/discovery.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    $buildArguments += @('--dart-define=ALLOW_DEMO_LOGIN=false', '--dart-define=PUBLIC_BUILD=true',
        "--dart-define=DISCOVERY_URL=$($publicDiscovery.url)", "--dart-define=SERVER_PUBLIC_KEY=$($publicDiscovery.public_key)",
        "--dart-define=SERVER_INSTANCE=$($publicDiscovery.instance)")
}
if ($Arm64) { $buildArguments += @('--target-platform', 'android-arm64') }
Push-Location -LiteralPath $buildMobile
try {
    # Native plugin builds read absolute package paths generated by pub get.
    & flutter.bat pub get --offline
    if ($LASTEXITCODE -ne 0) { throw "Flutter dependencies failed with exit code $LASTEXITCODE" }
    & flutter.bat @buildArguments
    if ($LASTEXITCODE -ne 0) { throw "Android build failed with exit code $LASTEXITCODE" }
    New-Item -ItemType Directory -Force -Path $buildArtifacts | Out-Null
    $buildOutputName = if ($Arm64) { 'pulse-uunit-arm64.apk' } else { 'pulse-uunit.apk' }
    if ($PublicServer) { $buildOutputName = if ($Arm64) { 'pulse-online-arm64.apk' } else { 'pulse-online.apk' } }
    $buildDestination = Join-Path $buildArtifacts $buildOutputName
    Copy-Item -LiteralPath (Join-Path $buildMobile 'build\app\outputs\flutter-apk\app-release.apk') -Destination $buildDestination -Force
    & (Join-Path $env:ANDROID_HOME 'build-tools\36.0.0\apksigner.bat') verify --verbose $buildDestination
    if ($LASTEXITCODE -ne 0) { throw 'APK signature verification failed.' }
    $buildFile = Get-Item -LiteralPath $buildDestination
    Write-Output "APK: $buildDestination"
    Write-Output ('Size: {0:N1} MB' -f ($buildFile.Length / 1MB))
    Write-Output ('SHA-256: ' + (Get-FileHash -LiteralPath $buildDestination -Algorithm SHA256).Hash)
} finally {
    Pop-Location
}
